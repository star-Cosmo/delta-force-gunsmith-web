// Convert simplified to traditional
function toTraditional(simplified) {
  let result = simplified;
  for (const [s, t] of Object.entries(s2t)) {
    result = result.replace(new RegExp(s, 'g'), t);
  }
  return result;
}

// Match an attachment.js name to extracted data
function findExtracted(attName) {
  // Direct match in extracted data
  if (extracted[attName]) return extracted[attName];
  
  // Try simplified version of attName
  // attName is already traditional, so we need to try matching simplified-then-back
  // Actually, attName is traditional in attachments.js, extracted keys are simplified
  // So we need to convert attName to simplified first
  
  // Try direct match with extracted keys
  for (const key of Object.keys(extracted)) {
    const tradKey = toTraditional(key);
    if (tradKey === attName) return extracted[key];
    if (key === attName) return extracted[key];
  }
  
  return null;
}

